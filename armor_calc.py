# 分析防具 0x45 和 0x47
# 已知:
# 6d(109) = 10级神器布甲
# 6e(110) = 10级神器轻甲
# 6f(111) = 10级神器重甲
# 70(112) = 10级神器板甲
# 每次等级+10，基数+4.
# 6d - 4 = 69 (0x45)!
# 等等! 6d (109) - 4 = 105 (0x69)! 不是 0x45!
# 0x45 = 69!
# 6d(109) - 0x45(69) = 40!
# 40 / 4 = 10 个档位!
# 或者:
# 看看 0x45 和 0x47:
# 0x44, 0x45, 0x46, 0x47 !
# 0x44: 布甲? 0x45: 轻甲? 0x46: 重甲? 0x47: 板甲?
# 或者 0x45 是轻甲/重甲?
# 0x47 - 0x45 = 2!
# 如果一组是 4 个 (布、轻、重、板):
# 0x44 (布), 0x45 (轻), 0x46 (重), 0x47 (板)!
# 恰好 0x45 是 轻甲，0x47 是 板甲!
print(f"0x44: 布甲")
print(f"0x45: 轻甲")
print(f"0x46: 重甲")
print(f"0x47: 板甲")

