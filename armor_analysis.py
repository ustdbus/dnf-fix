# 检查装备命名逻辑:
# 武器太刀已证明:
# 0x09: 40级普通太刀
# 0x28: 40级稀有太刀
# 0x39: 20级神器太刀
# 0x51: 30级史诗太刀

# 看看首饰:
# 0x29 ~ 0x33: 10级 ~ 60级 神器手腕 (粉手)
# 0x38 ~ 0x3a: 30级 ~ 50级 史诗手腕 (橙手)
# 那么 0x14 手腕:
# 如果 0x29(41) 往前推 10~11 个:
# 10级~60级 稀有手腕(紫手) = 0x14 ~ 0x1e !
# 0x14 正好就是第 1 个: 10级稀有手腕 (或者普通/高级手腕)

# 看看防具:
# 0x6d ~ 0x84: 10级 ~ 60级 神器防具 (粉防具，每级4个)
# 0x85 ~ 0x94, 0xba ~ 0xbd: 25级 ~ 60级 史诗防具 (橙防具，每级4个)
# 在 0x6d(109) 之前:
# 稀有防具 (紫防具):
# 60级紫: 0x69~0x6c
# 50级紫: 0x65~0x68
# 40级紫: 0x61~0x64
# 30级紫: 0x5d~0x60
# 20级紫: 0x59~0x5c
# 10级紫: 0x55~0x58
# 高级防具 (蓝防具):
# 60级蓝: 0x51~0x54
# 50级蓝: 0x4d~0x50
# 40级蓝: 0x49~0x4c
# 30级蓝: 0x45~0x48 ! (0x44布, 0x45轻, 0x46重, 0x47板)
# 或者:
# 稀有防具如果是按 5级 一档 (从 10级 到 60级 共有 11 档):
# 11 档 * 4 = 44 个!
# 0x6d (109) - 44 = 65 (0x41)!
# 那么 0x41~0x6c 正好是 11 档稀有防具 (10级~60级，每5级一档)!
# 如果稀有防具是每 5 级一档:
# 10级: 0x41~0x44 (布, 轻, 重, 板)
# 15级: 0x45~0x48 (0x45轻甲, 0x47板甲)!
# 或者:
# 20级: 0x45~0x48 (0x45轻甲, 0x47板甲)!
